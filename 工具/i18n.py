def set_lang(code: str) -> str:
    global _current
    code = (code or "zh").strip().lower()
    if code not in SUPPORTED:
        for k, lab in LANG_LABELS.items():
            if code == lab.lower() or code == lab:
                code = k
                break
        else:
            code = "zh"
    _current = code
    return _current


def t(key: str, **kwargs: Any) -> str:
    """当前语言文案；回退 en → zh → key。"""
    for code in (_current, "en", "zh"):
        block = _CATALOG.get(code) or {}
        if key in block and block[key]:
            s = block[key]
            break
    else:
        s = key
    if kwargs:
        try:
            return s.format(**kwargs)
        except Exception:
            return s
    return s


