def settings_path() -> str:
    if getattr(sys, "frozen", False):
        base = os.path.dirname(os.path.abspath(sys.executable))
    else:
        base = os.path.dirname(os.path.abspath(__file__))
    appdata = os.environ.get("APPDATA") or os.path.expanduser("~")
    cfg_dir = os.path.join(appdata, "InsuranceReportAssembler")
    try:
        os.makedirs(cfg_dir, exist_ok=True)
        return os.path.join(cfg_dir, "settings.json")
    except Exception:
        return os.path.join(base, "settings.json")


def load_saved_lang() -> str:
    path = settings_path()
    try:
        if os.path.isfile(path):
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
            return set_lang(str(data.get("language") or "zh"))
    except Exception:
        pass
    return set_lang("zh")


def save_lang(code: Optional[str] = None) -> None:
    code = set_lang(code or _current)
    path = settings_path()
    try:
        data: Dict[str, Any] = {}
        if os.path.isfile(path):
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f) or {}
        data["language"] = code
        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
    except Exception:
        pass


