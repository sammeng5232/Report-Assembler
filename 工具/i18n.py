def color_label_map() -> Dict[str, str]:
    keys = [
        ("color_black", "000000"), ("color_navy", "1F3864"), ("color_blue", "2E75B6"),
        ("color_lightblue", "5B9BD5"), ("color_red", "C00000"), ("color_darkred", "8B0000"),
        ("color_orange", "ED7D31"), ("color_gold", "BF8F00"), ("color_green", "375623"),
        ("color_teal", "548235"), ("color_purple", "7030A0"), ("color_gray", "595959"),
        ("color_darkgray", "404040"), ("color_lightgray", "7F7F7F"), ("color_white", "FFFFFF"),
    ]
    return {t(k): hx for k, hx in keys}


def hex_to_color_label(hex_str: Optional[str]) -> str:
    colors = color_label_map()
    if not hex_str:
        return t("color_black")
    h = str(hex_str).upper().replace("#", "").strip()
    for name, val in colors.items():
        if val.upper() == h:
            return name
    if len(h) != 6:
        return t("color_black")
    try:
        tr, tg, tb = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
    except ValueError:
        return t("color_black")
    best_name, best_d = t("color_black"), 1e18
    for name, val in colors.items():
        try:
            cr, cg, cb = int(val[0:2], 16), int(val[2:4], 16), int(val[4:6], 16)
        except ValueError:
            continue
        d = (tr - cr) ** 2 + (tg - cg) ** 2 + (tb - cb) ** 2
        if d < best_d:
            best_name, best_d = name, d
    return best_name


